let highlighterPromise: Promise<Highlighter> | null = null;
export function getHighlighter(): Promise<Highlighter> {
  highlighterPromise ??= createHighlighter({
    themes: [kitLightTheme, kitDarkTheme],
    langs: [...SHIKI_LANGS],
  });
  return highlighterPromise;
}

/** Collected token styles → short class names (shared across all pages of a build). */
export class TokenStyles {
  private map = new Map<string, string>();
  classFor(style: string): string {
    let c = this.map.get(style);
    if (!c) {
      c = `k${this.map.size.toString(36)}`;
      this.map.set(style, c);
    }
    return c;
  }
  css(): string {
    let out = '/* Generated by levimc-kit docs: Shiki token colours (light/dark via CSS variables). */\n';
    for (const [style, cls] of this.map) out += `.kit-shiki .${cls}{${style}}\n`;
    return out;
  }
}

