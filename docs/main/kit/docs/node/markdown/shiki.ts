function parseMeta(langRaw: string, meta: string) {
  // VitePress: ```js{1,3-4} [file.js]   pymdownx: ```py title="file.py" hl_lines="1 3" linenums="1"
  let lang = langRaw;
  let highlight = new Set<number>();
  let title: string | undefined;
  let lineNumbers: boolean | undefined;
  const braced = /^([^{]*)\{([\d,\s-]+)\}$/.exec(lang);
  if (braced) {
    lang = braced[1]!;
    for (const part of braced[2]!.split(',')) addRange(highlight, part);
  }
  const all = `${meta}`;
  const bm = /\{([\d,\s-]+)\}/.exec(all);
  if (bm) for (const part of bm[1]!.split(',')) addRange(highlight, part);
  const tm = /\[([^\]]+)\]/.exec(all) ?? /title="([^"]*)"/.exec(all);
  if (tm) title = tm[1];
  const hl = /hl_lines="([^"]*)"/.exec(all);
  if (hl) for (const part of hl[1]!.split(/\s+/)) addRange(highlight, part);
  if (/:line-numbers\b|linenums="[1-9]/.test(all)) lineNumbers = true;
  if (/:no-line-numbers\b/.test(all)) lineNumbers = false;
  return { lang, highlight, title, lineNumbers };
}
function addRange(set: Set<number>, part: string) {
  const m = /^\s*(\d+)(?:-(\d+))?\s*$/.exec(part);
  if (!m) return;
  const a = Number(m[1]);
  const b = m[2] ? Number(m[2]) : a;
  for (let i = a; i <= b; i++) set.add(i);
}

export async function highlightToHast(o: CodeOptions): Promise<Element> {
  const hl = await getHighlighter();
  const meta = parseMeta(o.lang, o.meta);
  const langKey = meta.lang.trim().toLowerCase();
  const target = o.aliases[langKey] ?? ALIASES[langKey] ?? langKey;
  const loaded = hl.getLoadedLanguages();
  const shikiLang = loaded.includes(target) ? target : 'text';
  const code = o.code.replace(/\n$/, '');
  const root = hl.codeToHast(code, {
    lang: shikiLang,
    themes: { light: 'levimc-light', dark: 'levimc-dark' },
    defaultColor: false,
    transformers: [
      {
        span(node) {
          const style = node.properties.style;
          if (typeof style === 'string' && style) {
            delete node.properties.style;
            const cls = o.styles.classFor(style);
            const prev = node.properties.class;
            node.properties.class = prev ? `${String(prev)} ${cls}` : cls;
          }
        },
        line(node, line) {
          if (meta.highlight.has(line)) this.addClassToHast(node, 'highlighted');
        },
        pre(node) {
          // Shiki uses raw `class`/`tabindex` keys; replace them (never mix with className/tabIndex).
          node.properties = { class: 'shiki kit-shiki', tabindex: '0' };
        },
      },
    ],
  }) as HastRoot;
  const pre = root.children.find((c): c is Element => c.type === 'element' && c.tagName === 'pre')!;
  const lines = code.split('\n').length;

  let titleText = '';
  let isFile = false;
  if (meta.title) {
    titleText = meta.title;
    isFile = true;
  } else if (o.codeTitle === 'pygments') {
    titleText = PYGMENTS_NAMES[langKey] ?? 'Text Only';
  } else if (o.codeTitle === 'lang') {
    titleText = langKey || 'text';
  }
  const showNumbers = (meta.lineNumbers ?? o.lineNumbers) && lines > 1;
  const head: Element = {
    type: 'element',
    tagName: 'div',
    properties: { className: ['kit-code-head'] },
    children: [
      ...(titleText
        ? [
            {
              type: 'element',
              tagName: 'span',
              properties: { className: isFile ? ['kit-code-title', 'is-file'] : ['kit-code-title'], dataKitCodeTitle: '' },
              children: [{ type: 'text', value: titleText }],
            } as Element,
          ]
        : [{ type: 'element', tagName: 'span', properties: { className: ['kit-code-title'], dataKitCodeTitle: '' }, children: [] } as Element]),
      {
        type: 'element',
        tagName: 'button',
        properties: {
          type: 'button',
          className: ['kit-code-copy'],
          dataKitCopy: '',
          ariaLabel: o.copyLabel,
          title: o.copyLabel,
          dataCopiedLabel: o.copiedLabel,
        },
        children: [{ type: 'raw', value: COPY_ICON + DONE_ICON } as unknown as ElementContent],
      },
    ],
  };
  return {
    type: 'element',
    tagName: 'div',
    properties: {
      className: ['kit-code'],
      dataLang: langKey || 'text',
      dataLines: String(lines),
      ...(showNumbers ? { dataLinenos: '', style: `--kit-gutter:${String(lines).length}ch` } : {}),
    },
    children: [head, pre],
  };
}
