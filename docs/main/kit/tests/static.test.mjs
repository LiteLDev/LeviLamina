// Unit tests for the static chrome: the no-JavaScript dark theme converter (static/nojs-dark.mjs, used for
// kit-nojs-dark.css and by the docs build) and the vanilla runtime static/kit.js (footer year, chrome-only
// translation). Run: node --test "kit/tests/*.test.mjs" (no dependencies).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { noJsDarkCss } from '../static/nojs-dark.mjs';

const read = (rel) => readFileSync(new URL(rel, import.meta.url), 'utf8');

// ------------------------------------------------------------------ noJsDarkCss
test('noJsDarkCss keeps the .dark selectors of each list in their @layer/@media/@supports context, .dark → :root', () => {
  assert.equal(
    noJsDarkCss(
      '@layer a,b;@layer a{.x{color:red}.dark .x,.y{color:blue}}@supports (a:b){.dark-mode{x:y}.z{a:"}"}}' +
        '@keyframes k{0%{opacity:0}}html.dark{color-scheme:dark}:where(.dark,.dark *) .q{a:b}@media (min-width:1px){.dark .m{c:d}}',
      { source: 'a test' },
    ),
    '/* generated by a test: its .dark rules (.dark → :root), loaded without JavaScript when the system theme is dark */\n' +
      '@layer a{:root .x{color:blue}}\nhtml:root{color-scheme:dark}\n:where(:root,:root *) .q{a:b}\n@media (min-width:1px){:root .m{c:d}}\n',
  );
});

test('noJsDarkCss: selector lists split only at top-level commas; braces in strings do not end a block', () => {
  assert.equal(
    noJsDarkCss('.a:is(.b,.dark),.dark .c{d:e}.f[data-x="a,b"],.dark .g{h:i}.i{content:".dark{"}.dark-x{y:z}'),
    '/* generated by static/build-static.mjs from kit.css: its .dark rules (.dark → :root), loaded without JavaScript when the system theme is dark */\n' +
      '.a:is(.b,:root),:root .c{d:e}\n:root .g{h:i}\n',
  );
});

test('noJsDarkCss rejects unbalanced CSS', () => {
  assert.throws(() => noJsDarkCss('.a{b:c}}'), /unbalanced/);
  assert.throws(() => noJsDarkCss('@media x{.dark .a{b:c}'), /unterminated/);
});

test('static/kit-nojs-dark.css holds every .dark rule of static/kit.css, with .dark → :root', () => {
  const kit = read('../static/kit.css');
  const css = read('../static/kit-nojs-dark.css');
  assert.equal(css, noJsDarkCss(kit), 'kit-nojs-dark.css is regenerated with kit.css');
  const body = css.replace(/^\/\*[^\n]*\*\/\n/, '');
  assert.ok(!/\.dark(?![\w-])/.test(body), 'no .dark selector left');
  // every rule of kit.css that names .dark is there (as many rules with :root as kit.css has with .dark;
  // each output rule keeps only the .dark selectors of its list)
  const rulesWith = (c, re) => [...c.matchAll(/([^{}]+)\{[^{}]*\}/g)].filter((m) => re.test(m[1])).length;
  assert.equal(rulesWith(body, /:root/), rulesWith(kit, /\.dark(?![\w-])/));
  assert.ok(body.includes('--color-canvas:#0f1b26'), 'dark tokens');
});

// ------------------------------------------------------------------ kit.js in a minimal DOM
const CHROME = '.kit-gbar, .kit-footer, .kit-skip-link, .kit-dox-drawer-network';

/** A fake element: `chrome` says whether it sits in the bar/footer/skip link (for matches/closest). */
function el({ text = '', attrs = {}, chrome = false } = {}) {
  const a = { ...attrs };
  const cls = new Set();
  return {
    textContent: text,
    tagName: 'SPAN',
    classList: { add: (c) => cls.add(c), remove: (c) => cls.delete(c), toggle: (c, on) => (on ?? !cls.has(c) ? cls.add(c) : cls.delete(c)), contains: (c) => cls.has(c) },
    getAttribute: (k) => (k in a ? a[k] : null),
    setAttribute: (k, v) => (a[k] = String(v)),
    hasAttribute: (k) => k in a,
    removeAttribute: (k) => delete a[k],
    matches: (sel) => sel === CHROME && chrome,
    closest: (sel) => (sel === CHROME && chrome ? {} : null),
    querySelector: () => null,
    attrs: a,
  };
}

/** Run kit.js once: `nodes` maps a selector kit.js queries to the fake elements it finds. */
function runKit({ nodes = {}, cookie = '', now } = {}) {
  const root = el({ attrs: { lang: 'en' } });
  root.style = {};
  root.lang = 'en';
  const listeners = [];
  const document = {
    documentElement: root,
    cookie,
    querySelectorAll: (sel) => nodes[sel] ?? [],
    querySelector: (sel) => (nodes[sel] ?? [])[0] ?? null,
    getElementById: () => null,
    addEventListener: (t) => listeners.push(t),
    visibilityState: 'visible',
  };
  const window = { matchMedia: () => ({ matches: false, addEventListener() {} }), addEventListener() {}, localStorage: null };
  const Clock = class extends Date {
    constructor(...args) {
      super(...(args.length ? args : [now ?? Date.now()]));
    }
  };
  vm.runInNewContext(read('../static/kit.js'), {
    document,
    window,
    location: { hostname: 'docs.levimc.org', protocol: 'https:' },
    requestAnimationFrame: () => {},
    Date: Clock,
    JSON,
    encodeURIComponent,
    decodeURIComponent,
  });
  return { root, listeners };
}

test('kit.js: the footer year only moves forward (the snippet carries its build year)', () => {
  const at = (now, built) => {
    const year = el({ text: String(built) });
    runKit({ nodes: { '[data-kit-year]': [year] }, now });
    return year.textContent;
  };
  assert.equal(at('2031-03-01T00:00:00Z', 2026), '2031');
  assert.equal(at('1970-01-02T00:00:00Z', 2026), '2026');
});

test('kit.js translates only the chrome into the stored language; page content keeps its text and lang', () => {
  const inBar = el({ text: 'Home', attrs: { 'data-kit-t': 'home' }, chrome: true });
  const blurbInMenu = el({ text: 'x', attrs: { 'data-kit-t': 'projectBlurbs.LeviLamina' }, chrome: true });
  const blurbOnPage = el({ text: 'Mod loader for Bedrock Dedicated Server', attrs: { 'data-kit-t': 'projectBlurbs.LeviLamina' } });
  const bar = el({ chrome: true });
  const option = el({ attrs: { 'data-kit-lang-value': 'en' } });
  const { root } = runKit({
    cookie: 'levimc_lang=ja',
    nodes: {
      '[data-kit-t]': [inBar, blurbInMenu, blurbOnPage],
      [CHROME]: [bar],
      '[data-kit-lang-value]': [option],
    },
  });
  assert.notEqual(inBar.textContent, 'Home', 'bar label translated');
  assert.notEqual(blurbInMenu.textContent, 'x', 'Docs menu blurb translated');
  assert.equal(blurbOnPage.textContent, 'Mod loader for Bedrock Dedicated Server', 'page content untouched');
  assert.equal(bar.attrs.lang, 'ja', 'the chrome gets lang=ja');
  assert.equal(blurbOnPage.attrs.lang, undefined);
  assert.equal(root.classList.contains('kit-chrome-pending'), false, 'the chrome is shown again');
});

test('kit.js localizes a project row (Doxygen header) to the nearest project locale, and back', () => {
  const tab = el({ text: 'User Guides', attrs: { href: '/LeviLamina/user_guides/install/', 'data-kit-l10n': JSON.stringify({ zh: ['用户指南', '/LeviLamina/zh/user_guides/install/'] }) } });
  const brand = el({ text: '', attrs: { href: '/LeviLamina/', 'data-kit-l10n': JSON.stringify({ zh: '/LeviLamina/zh/' }) } });
  const row = el({ attrs: { 'data-kit-site-locales': JSON.stringify([{ c: 'en', l: 'en' }, { c: 'zh', l: 'zh' }]) } });
  row.querySelectorAll = () => [tab, brand];
  runKit({ cookie: 'levimc_lang=zh-HK', nodes: { '[data-kit-site-locales]': [row] } });
  assert.equal(tab.textContent, '用户指南');
  assert.equal(tab.attrs.href, '/LeviLamina/zh/user_guides/install/');
  assert.equal(tab.attrs.lang, 'zh');
  assert.equal(brand.attrs.href, '/LeviLamina/zh/');
  assert.equal(brand.attrs.lang, undefined, 'href-only entries keep their content');
  // a later run with a preference that maps to no other locale restores the defaults
  runKit({ cookie: 'levimc_lang=fr', nodes: { '[data-kit-site-locales]': [row] } });
  assert.equal(tab.textContent, 'User Guides');
  assert.equal(tab.attrs.href, '/LeviLamina/user_guides/install/');
  assert.equal(tab.attrs.lang, undefined);
  assert.equal(brand.attrs.href, '/LeviLamina/');
});
