// ---------------------------------------------------------------- 4. kit.css (Tailwind v4)
const tmp = join(out, '.css-build');
await build({
  root: here,
  configFile: false,
  logLevel: 'warn',
  plugins: [tailwindcss()],
  build: {
    outDir: tmp,
    emptyOutDir: true,
    cssMinify: true,
    rollupOptions: { input: join(here, 'static-entry.css'), output: { assetFileNames: 'kit[extname]' } },
  },
});
const cssFile = readdirSync(tmp).find((f) => f.endsWith('.css'));
renameSync(join(tmp, cssFile), join(out, 'kit.css'));
