/** Remove `@layer a,b;` statements and unwrap `@layer x { … }` blocks (brace matching, strings respected). */
function unwrapLayers(css) {
  let s = css.replace(/@layer\s+[\w-]+(\s*,\s*[\w-]+)*\s*;/g, '');
  for (;;) {
    const m = /@layer\s+[\w-]+\s*\{/.exec(s);
    if (!m) break;
    let depth = 1;
    let i = m.index + m[0].length;
    let quote = null;
    for (; i < s.length && depth > 0; i++) {
      const c = s[i];
      if (quote) {
        if (c === '\\') i++;
        else if (c === quote) quote = null;
      } else if (c === '"' || c === "'") quote = c;
      else if (c === '{') depth++;
      else if (c === '}') depth--;
    }
    s = s.slice(0, m.index) + s.slice(m.index + m[0].length, i - 1) + s.slice(i);
  }
  return s;
}
