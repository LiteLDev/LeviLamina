#!/usr/bin/env node
// Builds the non-React chrome in static/ (run from an app that has the kit's dependencies installed):
//   globalbar.html, footer.html          GlobalBar (language + theme menus, GitHub) and SiteFooter as plain HTML (en)
//   i18n/globalbar.<locale>.html …       the same for every UI locale
//   theme-init.js, theme-init-doxygen.js pre-paint scripts (theme + language preference; load blocking in <head>)
//   theme-init-static.js                 the same for static pages whose chrome kit.js translates
//   kit.js                               vanilla runtime: theme/language menus, chrome translation, menus, year
//   kit.css                              compiled Tailwind v4 + full kit theme (covers all static markup)
//   kit-chrome.css                       chrome only, no preflight, layers unwrapped (Doxygen)
//   kit-nojs-dark.css                    kit.css's dark theme for readers without JavaScript
//   pages/index.html, pages/404.html     docs.levimc.org root: redirect page + themed 404
//   doxygen/header.html, doxygen/footer.html  Doxygen HTML_HEADER / HTML_FOOTER with the kit chrome
//
// Usage: node kit/static/build-static.mjs [--out <dir>] [--asset-base /levimc-kit/]
import { mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, createServer } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import { noJsDarkCss } from './nojs-dark.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const out = resolve(args.includes('--out') ? args[args.indexOf('--out') + 1] : here);
const assetBase = args.includes('--asset-base') ? args[args.indexOf('--asset-base') + 1] : '/levimc-kit/';
mkdirSync(join(out, 'i18n'), { recursive: true });
mkdirSync(join(out, 'pages'), { recursive: true });
mkdirSync(join(out, 'doxygen'), { recursive: true });

// ---------------------------------------------------------------- 1. snippets via SSR
const server = await createServer({ root: here, configFile: false, logLevel: 'error', server: { middlewareMode: true }, appType: 'custom', plugins: [react()] });
const snippets = await server.ssrLoadModule(join(here, 'snippets.tsx'));
const theme = await server.ssrLoadModule(join(here, '../components/theme.ts'));
const prefs = await server.ssrLoadModule(join(here, '../components/prefs.ts'));
const i18n = await server.ssrLoadModule(join(here, '../components/i18n.ts'));
const projects = await server.ssrLoadModule(join(here, '../components/projects.ts'));
const fonts = await server.ssrLoadModule(join(here, '../components/fonts.ts'));
const version = await server.ssrLoadModule(join(here, '../components/version.ts'));
await server.close();

const VERSION = readFileSync(join(here, '../VERSION'), 'utf8').trim();
if (VERSION !== version.KIT_VERSION) throw new Error(`VERSION (${VERSION}) and components/version.ts (${version.KIT_VERSION}) differ`);
const GENERATOR = `<meta name="generator" content="${version.KIT_GENERATOR}">`;

const banner = (what) => `<!-- levimc-kit ${VERSION} · ${what} · generated by static/build-static.mjs — do not edit -->\n`;
writeFileSync(join(out, 'globalbar.html'), banner('GlobalBar') + snippets.globalBarHtml({ locale: 'en' }) + '\n');
writeFileSync(join(out, 'footer.html'), banner('SiteFooter') + snippets.footerHtml({ locale: 'en' }) + '\n');
for (const loc of i18n.UI_LOCALES) {
  writeFileSync(join(out, 'i18n', `globalbar.${loc}.html`), banner(`GlobalBar ${loc}`) + snippets.globalBarHtml({ locale: loc }) + '\n');
  writeFileSync(join(out, 'i18n', `footer.${loc}.html`), banner(`SiteFooter ${loc}`) + snippets.footerHtml({ locale: loc }) + '\n');
}
const staticInit = theme.createThemeInitScript({ chromeLocales: i18n.UI_LOCALES });
const doxygenInit = theme.createThemeInitScript({ doxygen: true, chromeLocales: i18n.UI_LOCALES });
writeFileSync(join(out, 'theme-init.js'), theme.createThemeInitScript() + '\n');
writeFileSync(join(out, 'theme-init-static.js'), staticInit + '\n');
writeFileSync(join(out, 'theme-init-doxygen.js'), doxygenInit + '\n');

// ---------------------------------------------------------------- 2. kit.js (static/kit.src.js + preferences + chrome strings)
const CHROME_KEYS = [
  'home', 'projects', 'docs', 'packages', 'blog', 'community', 'about', 'network', 'menu', 'theme', 'themeAuto', 'themeLight', 'themeDark',
  'language', 'tagline', 'footerDocs', 'footerEcosystem', 'footerConnect', 'email', 'skipToContent',
];
const chromeStrings = Object.fromEntries(
  i18n.UI_LOCALES.map((loc) => {
    const t = i18n.UI_STRINGS[loc];
    return [loc, { ...Object.fromEntries(CHROME_KEYS.map((k) => [k, t[k]])), projectBlurbs: t.projectBlurbs }];
  }),
);
const json = (v) => JSON.stringify(v).replace(/</g, '\\u003c');
const kitJs = readFileSync(join(here, 'kit.src.js'), 'utf8')
  .replace('/*__PREFS_CORE__*/', () => prefs.PREFS_CORE_JS)
  .replace('/*__STRINGS__*/ {}', () => json(chromeStrings))
  .replace('/*__NAMES__*/ {}', () => json(i18n.UI_LOCALE_NAMES));
writeFileSync(join(out, 'kit.js'), `/* levimc-kit ${VERSION} · generated by static/build-static.mjs from static/kit.src.js — do not edit */\n` + kitJs);

// ---------------------------------------------------------------- 3. pages (docs.levimc.org root)
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// `first`: tags that must run before any stylesheet (a redirect does not wait for kit.css and the web fonts)
const head = (title, { first = '', extra = '' } = {}) => `<meta charset="utf-8">${first ? `\n  ${first}` : ''}
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${title}</title>
  ${GENERATOR}
  <meta name="color-scheme" content="light dark">
  <script>${staticInit}</script>
  ${fonts.FONT_HEAD_HTML}
  <link rel="stylesheet" href="${assetBase}kit.css">
  <noscript><link rel="stylesheet" href="${assetBase}kit-nojs-dark.css" media="(prefers-color-scheme: dark)"></noscript>
  <link rel="icon" href="${assetBase}grass.svg">${extra ? `\n  ${extra}` : ''}`;
const icon = (name) => `${assetBase}icons/${name.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}.svg`;
// the cards are page content (English, like the rest of the page): kit.js translates only the chrome
const docsCards = projects.DOCS_PROJECTS.map(
  (p) =>
    `<a class="px-card kit-card" href="${p.url}"><span class="kit-card-icon kit-slot"><img src="${icon(p.icon)}" width="32" height="32" alt="" class="pixelated"></span><span class="kit-card-body"><span class="kit-card-title">${p.name}</span> <span class="kit-card-desc">${esc(i18n.UI_STRINGS.en.projectBlurbs[p.id])}</span></span></a>`,
).join('\n        ');
const page = ({ title, first, extraHead, main }) => `<!doctype html>
<html lang="en">
<head>
  ${head(title, { first, extra: extraHead })}
</head>
<body>
  <a class="kit-skip-link" href="#kit-main" data-kit-t="skipToContent">${esc(i18n.UI_STRINGS.en.skipToContent)}</a>
  <div class="kit-backdrop" aria-hidden="true"><div class="kit-backdrop-dabs"></div><div class="kit-backdrop-brush"></div><div class="kit-backdrop-grain"></div></div>
  <div class="kit-backdrop-scene" aria-hidden="true"></div>
  <div class="kit-shell kit-above-backdrop">
  ${snippets.globalBarHtml({ locale: 'en', current: 'docs' })}
  <main id="kit-main" class="kit-static-main">
${main}
  </main>
  ${snippets.footerHtml({ locale: 'en' })}
  </div>
  <script src="${assetBase}kit.js" defer></script>
</body>
</html>
`;
writeFileSync(
  join(out, 'pages', 'index.html'),
  page({
    title: 'LeviMC Docs',
    first: `<link rel="canonical" href="https://levimc.org/">\n  <meta http-equiv="refresh" content="0; url=https://levimc.org/">\n  <script>location.replace("https://levimc.org/");</script>`,
    main: `    <section class="kit-static-card px-card kit-painted">
      <p class="kit-pixel-label kit-static-eyebrow">docs.levimc.org</p>
      <h1 class="kit-static-title">Redirecting to <a href="https://levimc.org/">levimc.org</a>…</h1>
      <p class="kit-static-text">Project documentation lives under docs.levimc.org/&lt;Project&gt;/:</p>
      <div class="kit-static-grid">
        ${docsCards}
      </div>
    </section>`,
  }),
);
writeFileSync(
  join(out, 'pages', '404.html'),
  page({
    title: 'Page not found | LeviMC Docs',
    extraHead: '<meta name="robots" content="noindex">',
    main: `    <section class="kit-static-card px-card kit-painted">
      <div class="kit-notfound-compass kit-slot" aria-hidden="true"><img src="${icon('compass')}" width="64" height="64" alt="" class="pixelated kit-notfound-spin"></div>
      <p class="kit-pixel-label kit-static-eyebrow">Error 404</p>
      <h1 class="kit-static-title">This page wandered off</h1>
      <p class="kit-static-text">Your compass is spinning — the page you are looking for does not exist or has moved. Pick a project:</p>
      <div class="kit-static-grid">
        ${docsCards}
      </div>
      <p class="kit-static-actions"><a class="mc-btn mc-btn-primary" href="https://levimc.org/">levimc.org</a></p>
    </section>`,
  }),
);

