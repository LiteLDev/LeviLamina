// kit-chrome.css: chrome only, no preflight, cascade layers unwrapped (for Doxygen and other foreign pages)
await build({
  root: here,
  configFile: false,
  logLevel: 'warn',
  plugins: [tailwindcss()],
  build: {
    outDir: tmp,
    emptyOutDir: true,
    cssMinify: true,
    rollupOptions: { input: join(here, 'chrome-entry.css'), output: { assetFileNames: 'kit-chrome[extname]' } },
  },
});
const chromeFile = readdirSync(tmp).find((f) => f.endsWith('.css'));
writeFileSync(join(out, 'kit-chrome.css'), unwrapLayers(readFileSync(join(tmp, chromeFile), 'utf8')));
rmSync(tmp, { recursive: true, force: true });

/** Remove `@layer a,b;` statements and unwrap `@layer x { … }` blocks (brace matching, strings respected). */
function unwrapLayers(css) {
  let s = css.replace(/@layer\s+[\w-]+(\s*,\s*[\w-]+)*\s*;/g, '');
  for (;;) {
    const m = /@layer\s+[\w-]+\s*\{/.exec(s);
    if (!m) break;
    let depth = 1;
    let i = m.index + m[0].length;
    let quote = null;
    for (; i < s.length && depth > 0; i++) {
      const c = s[i];
      if (quote) {
        if (c === '\\') i++;
        else if (c === quote) quote = null;
      } else if (c === '"' || c === "'") quote = c;
      else if (c === '{') depth++;
      else if (c === '}') depth--;
    }
    s = s.slice(0, m.index) + s.slice(m.index + m[0].length, i - 1) + s.slice(i);
  }
  return s;
}
