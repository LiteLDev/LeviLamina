// The kit's dark theme for readers without JavaScript (upstreamed from liteldev.github.io scripts/build-site.mjs).
// static/build-static.mjs writes static/kit-nojs-dark.css with it; static pages load that file inside <noscript>
// with media="(prefers-color-scheme: dark)". No dependencies.

const DARK = /\.dark(?![\w-])/;
const DARK_ALL = new RegExp(DARK.source, 'g');

/** Split a selector list at its top-level commas. */
function splitSelectors(list) {
  const out = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < list.length; i++) {
    const c = list[i];
    if (c === '(' || c === '[') depth++;
    else if (c === ')' || c === ']') depth--;
    else if (c === ',' && depth === 0) {
      out.push(list.slice(start, i));
      start = i + 1;
    }
  }
  out.push(list.slice(start));
  return out.map((s) => s.trim()).filter(Boolean);
}

/**
 * The kit's dark theme without JavaScript (also used by the docs build for each site's stylesheet). The kit switches themes with the `dark` class that its inline
 * theme-init script puts on <html>, so without JavaScript the pages are always light. This returns every rule
 * of kit.css that targets `.dark` (in its @layer/@media/@supports context, with only the `.dark` selectors of
 * each list), with `.dark` replaced by `:root`; the pages load it inside <noscript> with
 * media="(prefers-color-scheme: dark)". `.dark` is only ever set on the root element and kit.css has no
 * `:not(.dark)` selectors, so this applies exactly the rules the class would.
 * @param {string} css kit/static/kit.css or a site's built stylesheet (minified, flat — no CSS nesting)
 * @param {{ source?: string }} [opts] what generated it from what, for the banner comment
 */
export function noJsDarkCss(css, opts = {}) {
  const source = opts.source ?? 'static/build-static.mjs from kit.css';
  let i = 0;
  const n = css.length;
  const skipString = () => {
    const q = css[i++];
    while (i < n && css[i] !== q) i += css[i] === '\\' ? 2 : 1;
    i++;
  };
  const skipComment = () => {
    const end = css.indexOf('*/', i + 2);
    i = end < 0 ? n : end + 2;
  };
  /** Advance to the next top-level `{`, `;` or `}` and return what was skipped. */
  const prelude = () => {
    const start = i;
    let depth = 0;
    while (i < n) {
      const c = css[i];
      if (c === '"' || c === "'") skipString();
      else if (c === '/' && css[i + 1] === '*') skipComment();
      else {
        if (c === '(') depth++;
        else if (c === ')') depth--;
        else if (depth === 0 && (c === '{' || c === ';' || c === '}')) break;
        i++;
      }
    }
    return css.slice(start, i).trim();
  };
  /** Skip a declaration block (i is after its `{`); return its contents. */
  const block = () => {
    const start = i;
    let depth = 1;
    while (i < n) {
      const c = css[i];
      if (c === '"' || c === "'") skipString();
      else if (c === '/' && css[i + 1] === '*') skipComment();
      else {
        i++;
        if (c === '{') depth++;
        else if (c === '}' && --depth === 0) return css.slice(start, i - 1);
      }
    }
    throw new Error('kit.css: unterminated block');
  };
  const rules = (nested) => {
    const out = [];
    for (;;) {
      const head = prelude();
      const c = css[i++];
      if (c === undefined) {
        if (nested) throw new Error('kit.css: unterminated block');
        return out;
      }
      if (c === '}') {
        if (!nested) throw new Error('kit.css: unbalanced }');
        return out;
      }
      if (c === ';') continue; // @layer a,b; @charset; @import — the kit.css link already declared them
      if (/^@(media|supports|layer|container)\b/.test(head)) {
        const inner = rules(true);
        if (inner.length) out.push(`${head}{${inner.join('')}}`);
      } else {
        const body = block();
        if (head.startsWith('@')) continue; // @keyframes, @property, @font-face: not theme-dependent
        const dark = splitSelectors(head).filter((s) => DARK.test(s));
        if (dark.length) out.push(`${dark.map((s) => s.replace(DARK_ALL, ':root')).join(',')}{${body}}`);
      }
    }
  };
  const out = rules(false);
  return `/* generated by ${source}: its .dark rules (.dark → :root), loaded without JavaScript when the system theme is dark */\n${out.join('\n')}\n`;
}

