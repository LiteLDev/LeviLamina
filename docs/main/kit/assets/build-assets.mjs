#!/usr/bin/env node
// Regenerates pixel icons (SVG files + components/pixel-icons.ts) and the shared texture CSS
// (theme/generated.css: grass strip, brush texture, grain) from assets/sprites.mjs.
// Usage: node assets/build-assets.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sprites, grassStrip } from './sprites.mjs';
// Node ≥ 22.18 strips TypeScript types natively; paint.ts uses erasable syntax only.
import { lilyPond, harborSunrise, sceneToSvg } from '../components/paint.ts';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

function layersOf(name, sprite, w = 16, h = 16) {
  const { rows, palette } = sprite;
  const problems = [];
  if (rows.length !== h) problems.push(`${name}: expected ${h} rows, got ${rows.length}`);
  const byColor = new Map();
  rows.forEach((row, y) => {
    if (row.length !== w) problems.push(`${name}: row ${y} has ${row.length} chars: '${row}'`);
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.' || ch === ' ') {
        x++;
        continue;
      }
      let len = 1;
      while (x + len < row.length && row[x + len] === ch) len++;
      const fill = palette[ch];
      if (!fill) problems.push(`${name}: unknown colour key '${ch}' at ${x},${y}`);
      else {
        if (!byColor.has(fill)) byColor.set(fill, []);
        byColor.get(fill).push(`M${x} ${y}h${len}v1h-${len}z`);
      }
      x += len;
    }
  });
  return { layers: [...byColor.entries()].map(([fill, parts]) => [fill, parts.join('')]), problems };
}

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());

mkdirSync(join(root, 'assets/icons'), { recursive: true });
const allProblems = [];
const iconData = {};
for (const [name, sprite] of Object.entries(sprites)) {
  const { layers, problems } = layersOf(name, sprite);
  allProblems.push(...problems);
  iconData[name] = { title: sprite.title, layers };
  const mono = layers.every(([fill]) => fill === 'currentColor');
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16" shape-rendering="crispEdges"${mono ? ' fill="currentColor"' : ''}>` +
    `<title>${sprite.title}</title>` +
    layers.map(([fill, d]) => `<path fill="${fill}" d="${d}"/>`).join('') +
    `</svg>\n`;
  writeFileSync(join(root, 'assets/icons', `${kebab(name)}.svg`), svg);
}

const ts =
  `// Generated by assets/build-assets.mjs from assets/sprites.mjs — do not edit by hand.\n` +
  `// Each icon is a 16×16 grid; layers are [fill, pathData] drawn with shape-rendering="crispEdges".\n\n` +
  `export interface PixelIconData {\n  readonly title: string;\n  readonly layers: ReadonlyArray<readonly [fill: string, d: string]>;\n}\n\n` +
  `export const PIXEL_ICONS = ${JSON.stringify(iconData, null, 2)} as const satisfies Record<string, PixelIconData>;\n\n` +
  `export type PixelIconName = keyof typeof PIXEL_ICONS;\n`;
writeFileSync(join(root, 'components/pixel-icons.ts'), ts);

// ---------------------------------------------------------------- textures
const enc = (svg) =>
  `url("data:image/svg+xml,${svg
    .replace(/\s+/g, ' ')
    .replace(/%/g, '%25')
    .replace(/#/g, '%23')
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E')
    .replace(/"/g, "'")}")`;

const strip = layersOf('grassStrip', grassStrip, 16, 8);
allProblems.push(...strip.problems);
const stripSvg =
  `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 8' shape-rendering='crispEdges'>` +
  strip.layers.map(([fill, d]) => `<path fill='${fill}' d='${d}'/>`).join('') +
  `</svg>`;

// Seeded PRNG so the texture is reproducible.
function mulberry32(a) {
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = mulberry32(1872); // Impression, soleil levant was painted in 1872.
const T = 256;
const dabs = [];
for (let i = 0; i < 90; i++) {
  const cx = rnd() * T;
  const cy = rnd() * T;
  const rx = 9 + rnd() * 22;
  const ry = 1.6 + rnd() * 3.6;
  const rot = (rnd() - 0.5) * 18;
  const light = rnd() > 0.45;
  const op = (0.16 + rnd() * 0.34).toFixed(2);
  for (const dx of [-T, 0, T]) {
    for (const dy of [-T, 0, T]) {
      const x = cx + dx;
      const y = cy + dy;
      if (x + rx < -8 || x - rx > T + 8 || y + rx < -8 || y - rx > T + 8) continue;
      dabs.push(
        `<ellipse cx='${x.toFixed(1)}' cy='${y.toFixed(1)}' rx='${rx.toFixed(1)}' ry='${ry.toFixed(1)}' transform='rotate(${rot.toFixed(1)} ${x.toFixed(1)} ${y.toFixed(1)})' fill='${light ? '#fff' : '#000'}' opacity='${op}'/>`,
      );
    }
  }
}
const brushSvg =
  `<svg xmlns='http://www.w3.org/2000/svg' width='${T}' height='${T}' viewBox='0 0 ${T} ${T}'>` +
  `<filter id='p' x='0' y='0' width='100%' height='100%'>` +
  `<feTurbulence type='fractalNoise' baseFrequency='0.03 0.11' numOctaves='2' seed='4' stitchTiles='stitch' result='n'/>` +
  `<feDisplacementMap in='SourceGraphic' in2='n' scale='9' xChannelSelector='R' yChannelSelector='G' result='d'/>` +
  `<feGaussianBlur in='d' stdDeviation='0.6'/>` +
  `</filter>` +
  `<g filter='url(#p)'>${dabs.join('')}</g></svg>`;
const brushUri = enc(brushSvg);

const grainSvg =
  `<svg xmlns='http://www.w3.org/2000/svg' width='180' height='180'>` +
  `<filter id='g'><feTurbulence type='fractalNoise' baseFrequency='0.85' numOctaves='2' stitchTiles='stitch'/>` +
  `<feColorMatrix type='saturate' values='0'/></filter>` +
  `<rect width='100%' height='100%' filter='url(#g)' opacity='0.6'/></svg>`;

// Dark soil tile (footer): 16×16 speckled dirt, rendered at 2× with image-rendering: pixelated.
function dirtTile(seed, base, shades) {
  const r = mulberry32(seed);
  const rects = [];
  for (let y = 0; y < 16; y++)
    for (let x = 0; x < 16; x++) {
      const v = r();
      if (v < 0.24) rects.push([x, y, shades[Math.floor(r() * shades.length)]]);
    }
  const by = new Map();
  for (const [x, y, c] of rects) {
    if (!by.has(c)) by.set(c, []);
    by.get(c).push(`M${x} ${y}h1v1h-1z`);
  }
  return (
    `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 16' shape-rendering='crispEdges'><rect width='16' height='16' fill='${base}'/>` +
    [...by].map(([c, d]) => `<path fill='${c}' d='${d.join('')}'/>`).join('') +
    `</svg>`
  );
}
const dirtLight = enc(dirtTile(7, '#3d2b1f', ['#35251a', '#463223', '#4d3828', '#2f2117']));
const dirtDark = enc(dirtTile(7, '#1d150f', ['#18110c', '#231a12', '#281d15', '#140e09']));

// Painted backdrop scenes (lighter detail than the hero; used as cached CSS backgrounds on every page).
const paintLilies = enc(sceneToSvg(lilyPond({ bridge: false, detail: 0.55, height: 520, prefix: 'bl' })));
const paintSunrise = enc(sceneToSvg(harborSunrise({ boats: false, sunDisc: false, detail: 0.55, height: 520, prefix: 'bs', sunX: 0.86 })));

// Every sprite as a CSS data URI (colour sprites: background-image; currentColor glyphs: use as mask-image).
const iconVars = Object.entries(iconData)
  .map(([name, { layers }]) => {
    const svg =
      `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 16' shape-rendering='crispEdges'>` +
      layers.map(([fill, d]) => `<path fill='${fill === 'currentColor' ? '#000' : fill}' d='${d}'/>`).join('') +
      `</svg>`;
    return `  --kit-icon-${kebab(name)}: ${enc(svg)};`;
  })
  .join('\n');

const css = `/* Generated by assets/build-assets.mjs — do not edit by hand. Shared texture tokens. */
:root {
  /* 16×8 grass-over-dirt pixel strip (render at 2×: background-size 32px 16px; image-rendering: pixelated). */
  --kit-grass-strip: ${enc(stripSvg)};
  /* Impressionist brush-dab texture: ellipse dabs displaced by feTurbulence. Tile 256px, use at low opacity. */
  --kit-brush: ${brushUri};
  /* Fine canvas grain. */
  --kit-grain: ${enc(grainSvg)};
  /* Speckled soil (footer) for light / dark themes. */
  --kit-dirt: ${dirtLight};
  --kit-dirt-dark: ${dirtDark};
  /* Painted backdrop scenes: Nymphéas (light) and Impression, soleil levant (dark). */
  --kit-paint-lilies: ${paintLilies};
  --kit-paint-sunrise: ${paintSunrise};
  /* Pixel sprites (16×16). Monochrome glyphs are black: use them as mask-image with background: currentColor. */
${iconVars}
}
`;
writeFileSync(join(root, 'theme/generated.css'), css);

if (allProblems.length) {
  console.error('Sprite problems:\n  ' + allProblems.join('\n  '));
  process.exitCode = 1;
} else {
  console.log(`OK: ${Object.keys(sprites).length} icons, textures → theme/generated.css`);
}
